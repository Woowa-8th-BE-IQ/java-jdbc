package transaction.stage5;

import org.h2.jdbcx.JdbcDataSource;
import org.springframework.jdbc.core.JdbcTemplate;

import java.sql.Connection;
import java.sql.SQLException;
import java.util.UUID;

final class LocalDatabase implements AutoCloseable {

    private final JdbcDataSource dataSource;
    private final Connection anchor;
    private final JdbcTemplate jdbcTemplate;

    LocalDatabase() throws SQLException {
        dataSource = new JdbcDataSource();
        dataSource.setURL("jdbc:h2:mem:step5-" + UUID.randomUUID());
        anchor = dataSource.getConnection();
        jdbcTemplate = new JdbcTemplate(dataSource);
    }

    JdbcDataSource dataSource() {
        return dataSource;
    }

    JdbcTemplate jdbc() {
        return jdbcTemplate;
    }

    void createTable() {
        jdbcTemplate.execute("create table tx_records (id bigint generated by default as identity primary key, label varchar(100) not null)");
    }

    long count() {
        return jdbcTemplate.queryForObject("select count(*) from tx_records", Long.class);
    }

    @Override
    public void close() throws SQLException {
        anchor.close();
    }
}
